/* ★ 这两条**故意写在这里而不是 CubeMX 的 GUI 里**。
 *
 * 为什么：CubeMX 的 FREERTOS 配置参数表在 `config save` 时会把不认识的条目
 * 丢掉 —— 实测在 `.ioc` 里手写 FREERTOS.IPParameters=configCHECK_FOR_STACK_OVERFLOW,
 * configUSE_MALLOC_FAILED_HOOK 后重新生成，两者都被静默丢弃（.ioc 里只剩 Tasks01）。
 * 而 USER CODE 区是 CubeMX 明确承诺保留的（规矩 4），放这里不会丢。
 *
 * ⚠️ 若将来 CubeMX 的 GUI 里也能设这两项了，**只留一处** —— 两处都定义会触发
 *    "宏重定义"告警，而本工程要求零告警。
 *
 * 为什么值得开（本工程是 AI 参与开发的，故障必须**响亮**）：
 *   · configCHECK_FOR_STACK_OVERFLOW=2 —— 任务栈溢出是最难查的一类故障
 *     （现象是"随机跑飞"）。开 2 会在每次任务切换时检查栈尾的两个哨兵字，
 *     溢出立刻调 vApplicationStackOverflowHook（见 Device/Src/bsp_fault.c）。
 *     代价：每次切换多几条指令，可忽略。
 *   · configUSE_MALLOC_FAILED_HOOK=1 —— 堆耗尽时 pvPortMalloc 返回 NULL，
 *     不开钩子就是"静默失败"，开了会调 vApplicationMallocFailedHook。
 *     ⚠️ 钩子内部**不能取锁**（堆已经没了，建锁还会再失败）——见 bsp_log.h
 *        的 bsp_log_printf_nolock()。两个钩子的实现都在 Device/Src/bsp_fault.c。
 *
 * ⚠️ 忘了实现钩子**不会报错** —— cmsis_os2.c 里有一份 __WEAK 空实现兜着，
 *    于是"开关开了但什么都不发生"。bsp_fault.c 里的强定义会覆盖它。 */
#define configCHECK_FOR_STACK_OVERFLOW 2
#define configUSE_MALLOC_FAILED_HOOK   1

