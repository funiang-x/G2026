/* ------------------------------------------------------ 找峰扫带（op_peak）----
 * ★ 2026-10-07 从 `app_engine.c` 的硬编码字面量上提到这里（本工程禁止魔数）。
 *
 * ⚠️ **[9000, 502000] 不是"比题面松一点"，是找峰下标算法的**最小可行值**。
 *    推导（op_peak.c 的下标算术，`df = fs/N = 2000000/4096 = 488.28125 Hz`）：
 *      · 下端：`k_lo = (int)(f_lo/df)`，而局部极大搜索**从 k_lo+1 起步**。
 *        题面下界 10 kHz 的栅格主峰在 `k = (int)(10000/df) = 20`。
 *        ⇒ 必须 `k_lo ≤ 19` ⇒ `f_lo < 20·df = 9765.6 Hz`。取 9000（k_lo=18）留 1 bin 余量。
 *        ⚠️ 若把 f_lo 写成 10000，k_lo=20、搜索从 21 起 ⇒ **10 kHz 的峰会整个漏掉**。
 *      · 上端：循环条件 `while (k < k_hi - 3)` ⇒ 最后一个被测下标是 `k_hi-4`。
 *        题面上界 500 kHz 恰好落在 `k = 500000/df = 1024.0`（整数周期，无泄漏）。
 *        ⇒ 必须 `k_hi - 4 ≥ 1024` ⇒ `k_hi ≥ 1028` ⇒ `f_hi ≥ 1027.96·df ≈ 501.95 kHz`。
 *        取 502000（k_hi=1028）**刚好够**。
 *        ⚠️ 若把 f_hi 写成 500000，k_hi=1024、最后测到 1020 ⇒ **500 kHz 的峰漏掉**。
 *    ⇒ 结论：这两个数**贴着算法边界**，不能"凑整"成 10k/500k。
 *      `app_engine_init()` 里有一道运行期自检（改 fs / OP_DSP_N 会当场报 ERROR）。
 *
 * gate = 1.5 mV：> 最坏混叠残留 0.65 mV（防假线），< 最小真分量影响判据。
 * 依据：`op_peak.h` 的 ② 段 + 复算（`tools/sim/` 折叠带最差 −57.4 dB ⇒ 250mV 输入
 * 折到 ADC 端 0.34 mV）。
 * ⚠️ 这三个值在 `op_peak.c` 的静态默认值里有一份**同值拷贝**（PC 单测的兜底，
 *    Operation 层不许读配置头）—— 改这里必须同步那边。 */
#define APP_PEAK_F_LO_HZ 9000.0f
#define APP_PEAK_F_HI_HZ 502000.0f
#define APP_PEAK_GATE_MV 1.5f

