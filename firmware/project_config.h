/* draw buffer 的行数：缓冲 = **逻辑宽** × 本值 × 2 字节。
 *   480 × 56 × 2 = 53.8 KB（在 SRAM1，见 Task/Src/app_lvgl.c）。
 *   ⚠️ 宽度是**逻辑宽 480**（横屏后），不是面板物理宽 320 —— 旧注释写的
 *      "320 × 48 × 2 = 30.7 KB" 是竖屏时代的口径，2026-10-14 订正。
 * ⚠️ 调大省 flush 次数（FSMC 每次开窗有固定开销），但吃 RAM。
 *    **2026-10-14 S6：48 → 56** —— 整屏重绘的**带数 7 → 6**
 *    （`ceil(320/48)=7`，`ceil(320/56)=6`）⇒ 每帧少一次"渲染 + flush + 带切换"。
 *    选 56 而不是 64：64 也是 5 带但要多 15 KB RAM（门禁余量只剩 2.7 KB，太紧）；
 *    56 只需 +7.5 KB、余量 10.2 KB，而且**带数与 64 只差 1**。
 *    再大（80 行 = +30 KB）会**直接撞穿 120 KB 体积门禁**。
 * ⚠️ 这个缓冲**不能放 CCM**：本工程走 CPU 直写 FSMC 时能跑，
 *    但将来若改成 DMA 搬 FSMC，CCM 会**静默失效**（不报错、花屏/黑屏）。
 *    放 SRAM1 就没有这个隐患，代价只是访问慢一点点。
 *
 * ★ 2026-10-14（C9②③）：**56 → 28，为 DMA 双缓冲定的**。
 *   为什么是 28：异步 flush（DMA）要求**两块** buffer，而横向逻辑宽是 **480**
 *   ⇒ 每块 = 480 × 行数 × 2 B。两块总量不能超过原来单块 480×56×2 = 53.76 KB
 *   ⇒ 行数 ≤ 28。取 28 = 26.25 KB/块、两块 **52.5 KB**（与原来基本持平）。
 *   代价：整屏带数 **6 → 18**（480/28=17.14 ⇒ 18 带）。
 * ★ 已实测的代价（**可复现测试台**，`_work/lvgl_band_ab_20261014/`，2026-10-14）：
 *   带数 6 → 18 时，**flush/帧几乎不变**（10.80 → 10.82 ms，带数在 flush 侧几乎免费），
 *   但 **render/帧 +2.57 ms**（7.40 → 9.97），即 **每多一带 ≈ +0.64 ms**（全在 render 侧）。
 *   ⇒ 换来的是把 flush 那 ≈14.3 ms/帧 藏到渲染背后（净赚 ≈6.6 ms/帧）。
 * ⇒ 结论（2026-10-14 定稿）：**56 行**（整屏 6 带）。28 行只在那条已放弃的
 *   "DMA 双缓冲"路线下才有意义（两块各 28 行）；那条路已按结论清理，
 *   所以这里回到 56 —— 它是**非 DMA 配置下的最优带数**。 */
#define APP_LVGL_DRAW_BUF_LINES 56U



/* ★ 横屏逻辑分辨率（2026-10-13 起界面固定横屏）。
 *
 * ⚠️ 这**不是**面板的物理尺寸（那是 `board_config.h` 的 BOARD_LCD_WIDTH/HEIGHT =
 *    320×480），而是 **LVGL 的逻辑坐标系** —— `app_lvgl.c` 把 display 旋转 90° 之后，
 *    `lv_display_get_horizontal_resolution()` 返回的就是这两个值。
 *    UI 布局、draw buffer 的一行宽度、坐标显示**一律按逻辑尺寸算**。
 *
 * 为什么是 480×320：ROTATION_90 = 把面板**顺时针**转 90°。依据是 LVGL 自己的
 *    `lv_display_rotate_point()`（`display/lv_display.c`）在 90° 下写的是
 *    `x' = ver_res - y - 1; y' = x` —— 与"绕中心顺时针旋转 90°"逐点一致
 *    （面板左上角 → 逻辑右上角），不是逆时针。
 * ⚠️ 触摸坐标**不用**我们手工转：`lv_indev_read()` 读完 indev 后自动调
 *    `lv_display_rotate_point()`（`indev/lv_indev.c`）⇒ `bsp_touch_read()` 给的必须是
 *    **面板物理坐标**（320×480 口径），旋转由 LVGL 负责。换方向时**只改**
 *    `app_lvgl.c` 的 `lv_display_set_rotation()` 那一处，别去动 MADCTL / bsp_lcd。 */
#define APP_LVGL_SCR_W 480U
#define APP_LVGL_SCR_H 320U

/* ★ LVGL 重绘周期（ms）：**帧率的第一瓶颈在这里，不在 FSMC**。
 *
 * 机理：显示刷新跑在一个周期定时器上（`disp->refr_timer`，初值 = `lv_conf.h` 的
 *   `LV_DEF_REFR_PERIOD` = 16ms），而**官方 sysmon 报的 FPS 上限就是 `1000/period`**
 *   —— `lv_sysmon.c` 的 `perf_dump_info()` 里有一句
 *   `fps = LV_MIN(fps, 1000 / disp_refr_period)`。⇒ period=16 时，无论实际多快，
 *   屏上永远看不到 62.5 以上的数。
 * 取 **10 = 与 `APP_TICK_PERIOD_MS` 对齐**：`lv_timer_handler()` 每 10ms 才被调一次
 *   （见 `app_ui_task`），周期设得比它小不会让 LVGL 更勤地被检查。
 *   ⇒ 本工程的**重绘率上限 = 100 fps**。
 * ⚠️ 再往小调（如 5ms）没有任何提升，只会让 sysmon 显示一个够不到的上限。
 * ⚠️ 这是**重绘**帧率；`app_lvgl_fps_x10()` 报的是另一个口径（像素吞吐 ÷ 整帧），
 *    两者不可互相印证（见 app_lvgl.c）。 */
#define APP_LVGL_REFR_PERIOD_MS 10U

/* ★ 2026-10-14 S4：**触摸读定时器的周期**（ms）。
 *
 * why：滑动的"跟手度"上限就是它 —— 手指动了最多要等一个采样周期才被读到。
 *   `lv_indev` 的读定时器默认跟 lv_conf.h 的 `LV_DEF_REFR_PERIOD`(16ms) ⇒ 上限 62.5Hz
 *   （板上实测 `[TOUCH] 1s: 采样 50`）。收到 10 ⇒ 上限 100Hz。
 * ⚠️ 只动这一个定时器（`app_lvgl.c` 里 `lv_indev_get_read_timer()`），
 *   **不要**去改 `LV_DEF_REFR_PERIOD` —— 那是全局初值，会连带把重绘周期也改掉。
 * ⚠️ 代价：I2C 读次数翻倍（每次 ~7 B @100kHz ≈ 0.7ms）⇒ UI 任务多约 3.5% CPU。
 *   采样窗内无影响（那时 UI 在忙等 `app_engine_acquiring()`，不读触摸）。 */
#define APP_TOUCH_READ_PERIOD_MS 10U

/* ★ 2026-10-14：**UI 业务刷新的最小间隔**（ms）—— 一道"防连续重测"的闸。
 *
 * why 要从 100 收到 20（用户要求："接入信号要及时刷出来，切换参数要尽快算出来显示"）：
 *   数据本身只有 **10 Hz**（测量周期 `APP_MEAS_PERIOD_MS` = 100ms），
 *   而闸门原来也是 100ms ⇒ **两个同周期、彼此不同步的计时器会锁在一个任意的
 *   固定相位差上** ⇒ 最坏给"发布 → 上屏"白加 **100 ms**。
 *   收到 20ms 后这段最坏只剩 20ms，而**负载上限仍被闸门兜住**（最坏 50 次/s）。
 *
 * ⚠️ **闸门不能删**：`app_engine_remeasure()`（切页 / 换 1T-3T）会让 engine 立刻重测，
 *    连点几下就是一波"连续重测"——闸门就是防它的（2026-10-13 四轮的原始动机）。
 * ⚠️ 2026-10-13 那条动机里的"重建波形 + 重启三处滚入动画"**已经不成立**了：
 *    滚入动画八轮已删、波形八轮加了变化检测、2026-10-14 起无信号时画直线 ⇒ 刷新很便宜。
 *    ⇒ 闸门只需要挡住"突发"，不需要挡住"正常 10Hz"。 */
/* ★ 2026-10-14：页面"按需加载 + 用后销毁"的**销毁推迟时长**（ms）。
 *
 * 为什么不离开就立刻删：`lv_tileview` 的翻页是**拖动动画**，动画期间老页仍在屏幕上
 *   ⇒ 立刻删就是**半屏空白**（"切换流畅、销毁不影响体验"这条要求的落点）。
 * 500ms 的来历：翻页动画是百毫秒量级（LVGL 默认 ~300ms）+ 一拍 10ms 的余量。
 *   ⚠️ 别调太大：来回快速滑动时多驻留一页 = 池峰值高一页（把需求 2 的收益吃回去）。
 *   ⚠️ 别调太小（小于一个动画时长）：会白屏。判据：滑动过程**不该**看到任何空白。 */
#define APP_UI_PAGE_FREE_DELAY_MS 500U

#define APP_UI_REFR_MIN_MS 20U

/* ★ LCD 写屏的"可打断粒度"（像素）：采样窗静默（硬件方案 02 §6 O1）靠它落地。
 *
 * 为什么需要：LVGL 的 flush 是**同步**的，一个 draw buffer = 480×48 px 的 FSMC 连续写
 * （现行 FSMC 时序 AS=2/DS=8 ⇒ 76.4 ns/字 ⇒ **≈1.17 ms**；见 board_config.h 的
 *  FSMC 段）。采样窗只有 2.048 ms —— 量级相当，所以"能不能在块边界被打断"是必须的。
 *
 * 机制（Task 层"LCD 总线闸"，实现在 app_engine.c）：
 *   · engine **开采集之前**先抢闸、采完放闸；
 *   · 写屏侧每写 `APP_LCD_CHUNK_PX` 像素抢一次闸。
 * ⇒ 采样窗内一次写屏都不会发生；代价是 engine 起采最多晚 1 块、flush 被推迟 ≤2ms。
 * ⚠️ 调大 = 信号量开销少但 engine 等得久；调小 = 打断更细但调用更频繁。
 *    1024 px @ 76.4 ns/字 ≈ **0.078 ms** —— 相对 2.048 ms 的采样窗已足够细，
 *    所以维持 1024 不变（原注释按已作废的 DS=85 写成 0.6ms）。 */
#define APP_LCD_CHUNK_PX 1024U

/* 抢 LCD 总线闸的等待上限（ms）：正常只需等"当前块"写完（1024 px ≈0.11ms）。
 * 给到 20ms 是**防御性**的：万一写屏侧漏了 give，engine 也不能被永久堵死
 * ——超时后照常开采集（退化成旧的整帧级避让，不比改前差）。 */
#define APP_LCD_BUS_WAIT_MS 20U

